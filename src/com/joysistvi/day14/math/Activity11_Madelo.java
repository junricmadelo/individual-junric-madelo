package com.joysistvi.day14.math;

public class Activity11_Madelo {

    public static void main(String[] args){

        //Absolute value, 50 - 70 = -20  ( 20 )
        // ginagawa nitong positive ang negative number. Ang -20 ay nagiging 20.

        int num1  =  50;
        int num2  =  70;
        int difference = Math.abs(num1 - num2);

        System.out.println("Difference: " + difference); // = 20
    }
}
